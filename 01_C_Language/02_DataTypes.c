#include <stdio.h>


int main() {

    int num = 12;                // integer data type
    char letter = 'A';           // character data type
    float decimal = 3.14;        // float data type

    // print the values of data types
    printf("Integer: %d\n", num);
    printf("Character: %c\n", letter);
    printf("Float: %f\n", decimal);
    return 0;
}